# Android vectors

def vector(body: str, size: int = 108, viewport: int = 108, aapt: bool = False) -> str:
    ns = ' xmlns:aapt="http://schemas.android.com/aapt"' if aapt else ""
    return (f'<?xml version="1.0" encoding="utf-8"?>\n'
            f'<!-- Generated by tools/brand.py; edit the script, not this file. -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"{ns}\n'
            f'    android:width="{size}dp" android:height="{size}dp"\n'
            f'    android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">\n'
            f'{body}</vector>\n')


def stroke(d: str, color: str, width: float, alpha: float = 1.0, join: str = "round") -> str:
    a = f' android:strokeAlpha="{alpha:g}"' if alpha < 1 else ""
    return (f'    <path android:pathData="{d}"\n'
            f'        android:strokeColor="{color}" android:strokeWidth="{width:g}"{a}\n'
            f'        android:strokeLineCap="round" android:strokeLineJoin="{join}" />\n')


def fill(d: str, color: str, alpha: float = 1.0, even_odd: bool = False) -> str:
    a = f' android:fillAlpha="{alpha:g}"' if alpha < 1 else ""
    t = ' android:fillType="evenOdd"' if even_odd else ""
    return f'    <path android:pathData="{d}" android:fillColor="{color}"{a}{t} />\n'


def rounded_rect(x: float, y: float, w: float, h: float, r: float) -> str:
    return (f"M{x + r:g},{y:g} H{x + w - r:g} A{r:g},{r:g} 0 0 1 {x + w:g},{y + r:g} "
            f"V{y + h - r:g} A{r:g},{r:g} 0 0 1 {x + w - r:g},{y + h:g} H{x + r:g} "
            f"A{r:g},{r:g} 0 0 1 {x:g},{y + h - r:g} V{y + r:g} A{r:g},{r:g} 0 0 1 {x + r:g},{y:g} Z")


def circle(cx: float, cy: float, r: float) -> str:
    return f"M{cx - r:g},{cy:g} a{r:g},{r:g} 0 1 0 {2 * r:g},0 a{r:g},{r:g} 0 1 0 {-2 * r:g},0 Z"


