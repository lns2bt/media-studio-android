def svg_mark(scale: float, ox: float, oy: float, animated: bool = False, plate: bool = True,
             uid: str = "m") -> str:
    """The launcher icon as SVG, drawn at [scale] units per icon unit."""
    s = scale
    out = [f'<g transform="translate({ox:g},{oy:g}) scale({s:g})">']
    if plate:
        out.append(f'''<defs>
  <linearGradient id="{uid}bg" x1="0" y1="0" x2="1" y2="1">
    <stop offset="0" stop-color="{TEAL_HI}"/><stop offset=".55" stop-color="{TEAL}"/><stop offset="1" stop-color="{DEEP}"/>
  </linearGradient>
  <radialGradient id="{uid}glow" cx="54" cy="50" r="46" gradientUnits="userSpaceOnUse">
    <stop offset="0" stop-color="{MINT}" stop-opacity=".2"/><stop offset="1" stop-color="{MINT}" stop-opacity="0"/>
  </radialGradient>
</defs>
<rect x="16" y="16" width="76" height="76" rx="22" fill="url(#{uid}bg)"/>
<rect x="16" y="16" width="76" height="76" rx="22" fill="url(#{uid}glow)"/>''')
    out.append(f'<g transform="translate(54,54) scale({MARK_SCALE}) translate(-54,-54)">')
    out.append(f'<rect x="{LEFT}" y="{TOP}" width="{RIGHT - LEFT}" height="{BOTTOM - TOP}" rx="5" '
               f'fill="{MINT}" fill-opacity=".14"/>')
    for i, (x, h, inside) in enumerate(BARS):
        x1, y1, x2, y2 = bar_line(x, h)
        color, opacity = ("#FFFFFF", 1) if inside else (MINT, .5)
        cls = f' class="bar b{i}"' if animated else ""
        out.append(f'<line{cls} x1="{x1:g}" y1="{y1:g}" x2="{x2:g}" y2="{y2:g}" stroke="{color}" '
                   f'stroke-opacity="{opacity}" stroke-width="{BAR_W}" stroke-linecap="round"/>')
    out.append(f'<path d="{brackets()}" fill="none" stroke="{MINT}" stroke-width="3.4" '
               f'stroke-linecap="round" stroke-linejoin="round"/>')
    out.append("</g></g>")
    return "\n".join(out)


def wave_heights(n: int, seed: float = 1.7, word: tuple[float, float] = (0.3, 0.7)) -> list[float]:
    """A deterministic, speech-like envelope in 0..1: soft "words" with a little texture,
    the loudest one inside [word] so the selection holds the interesting part."""
    a, b = word
    mid, span = (a + b) / 2, (b - a)
    words = [(0.06, 0.05, 0.35), (0.17, 0.05, 0.5), (a + span * 0.22, span * 0.17, 0.75),
             (mid + span * 0.05, span * 0.16, 1.0), (b - span * 0.18, span * 0.14, 0.7),
             (0.86, 0.05, 0.45), (0.96, 0.04, 0.3)]
    out = []
    for i in range(n):
        t = i / (n - 1)
        level = sum(amp * math.exp(-((t - c) / w) ** 2) for c, w, amp in words)
        texture = 0.78 + 0.22 * (math.sin(i * 12.9898 + seed * 78.233) * 43758.5453 % 1.0)
        out.append(max(0.07, min(1.0, (0.08 + level) * texture)))
    return out


def trimmed_wave(n: int, x0: float, x1: float, cy: float, hmax: float, a: int, b: int, width: float,
                 sel: str, dim: str, seed: float, animated: bool) -> tuple[str, float, float]:
    """Bars a..b-1 are selected; the slots a-1 and b stay empty for the brackets."""
    step = (x1 - x0) / (n - 1)
    hs = wave_heights(n, seed=seed, word=(a / (n - 1), (b - 1) / (n - 1)))
    bars = []
    for i, v in enumerate(hs):
        if i in (a - 1, b):
            continue
        x = x0 + i * step
        h = 10 + v * hmax
        color = sel if a <= i < b else dim
        anim = f' class="w" style="animation-delay:{(i % 9) * .17:.2f}s"' if animated else ""
        bars.append(f'<line{anim} x1="{x:.1f}" y1="{cy - h / 2:.1f}" x2="{x:.1f}" y2="{cy + h / 2:.1f}" '
                    f'stroke="{color}" stroke-width="{width:g}" stroke-linecap="round"/>')
    return "".join(bars), x0 + (a - 1) * step, x0 + b * step


