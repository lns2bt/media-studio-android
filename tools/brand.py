# ---------------------------------------------------------------------------
# The mark, on Android's 108-unit adaptive icon canvas (safe zone: r=33 at 54,54).

CY = 54
# (x, height, inside the selection)
BARS = [
    (26, 10, False), (33, 17, False),
    (40, 23, True), (47, 37, True), (54, 27, True), (61, 33, True), (68, 19, True),
    (75, 15, False), (82, 9, False),
]
BAR_W = 4.6
LEFT, RIGHT, TOP, BOTTOM, ARM = 36.0, 72.0, 32.0, 76.0, 5.5
# The launcher draws the mark smaller than its geometry, leaving calm space inside any mask.
MARK_SCALE = 0.8


def bar_line(x: float, h: float) -> tuple[float, float, float, float]:
    return x, CY - h / 2, x, CY + h / 2


def brackets() -> str:
    return (f"M{LEFT + ARM},{TOP} H{LEFT} V{BOTTOM} H{LEFT + ARM} "
            f"M{RIGHT - ARM},{TOP} H{RIGHT} V{BOTTOM} H{RIGHT - ARM}")


def bars_path(selected: bool | None) -> str:
    parts = []
    for x, h, inside in BARS:
        if selected is None or inside == selected:
            x1, y1, x2, y2 = bar_line(x, h)
            parts.append(f"M{x1:g},{y1:g} L{x2:g},{y2:g}")
    return " ".join(parts)


