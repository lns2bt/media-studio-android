def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print("wrote", path.relative_to(ROOT))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--preview", action="store_true", help="render PNG previews of the SVG artwork")
    args = parser.parse_args()

    write(RES / "drawable/ic_launcher_background.xml", launcher_background())
    write(RES / "drawable/ic_launcher_foreground.xml", launcher_foreground())
    write(RES / "drawable/ic_launcher_monochrome.xml", launcher_monochrome())
    write(RES / "drawable/ic_stat_studio.xml", status_icon())
    write(RES / "drawable/ic_shortcut_paste.xml", shortcut(LINK_GLYPH))
    write(RES / "drawable/ic_shortcut_file.xml", shortcut(FILE_GLYPH))

    write(DOCS / "icon.svg", f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="16 16 76 76" width="256" height="256">\n'
                             f'{svg_mark(1, 0, 0, uid="i")}\n</svg>\n')
    write(DOCS / "banner-light.svg", banner(dark=False))
    write(DOCS / "banner-dark.svg", banner(dark=True))
    write(DOCS / "pipeline-light.svg", pipeline(dark=False))
    write(DOCS / "pipeline-dark.svg", pipeline(dark=True))
    write(DOCS / "feature-extractor.svg", feature_icon("extractor"))
    write(DOCS / "feature-converter.svg", feature_icon("converter"))
    social = DOCS / "social-preview.svg"
    write(social, social_preview())

    renderer = shutil.which("rsvg-convert")
    if renderer:
        # GitHub's social preview must be uploaded as an image; keep a PNG next to its source.
        subprocess.run([renderer, "-w", "1280", "-h", "640", "-o", str(DOCS / "social-preview.png"), str(social)],
                       check=True)
        print("wrote", (DOCS / "social-preview.png").relative_to(ROOT))
        if args.preview:
            out = ROOT / "build/brand-preview"
            out.mkdir(parents=True, exist_ok=True)
            for svg in DOCS.glob("*.svg"):
                subprocess.run([renderer, "-z", "1", "-o", str(out / (svg.stem + ".png")), str(svg)], check=True)
            print("previews in", out.relative_to(ROOT))


if __name__ == "__main__":
    main()
