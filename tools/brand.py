def group(body: str, scale: float, pivot: float) -> str:
    inner = "".join("    " + line + "\n" for line in body.rstrip("\n").split("\n"))
    return (f'    <group android:pivotX="{pivot:g}" android:pivotY="{pivot:g}" '
            f'android:scaleX="{scale:g}" android:scaleY="{scale:g}">\n{inner}    </group>\n')


def launcher_foreground() -> str:
    body = (fill(rounded_rect(LEFT, TOP, RIGHT - LEFT, BOTTOM - TOP, 5), MINT, 0.14)
            + stroke(bars_path(False), MINT, BAR_W, 0.5)
            + stroke(bars_path(True), "#FFFFFF", BAR_W)
            + stroke(brackets(), MINT, 3.4))
    return vector(group(body, MARK_SCALE, 54))


